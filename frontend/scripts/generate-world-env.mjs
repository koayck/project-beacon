import fs from 'node:fs'
import path from 'node:path'
import { z } from 'zod'

const root = process.cwd()

function parseArgs(argv) {
  const defaults = {
    world: '../shared/world2.json',
    out: 'src/generated/world2Environment.generated.ts',
    constName: 'WORLD2_ENV',
  }

  const args = { ...defaults }
  for (let i = 0; i < argv.length; i += 1) {
    const token = argv[i]
    if (token === '--world') args.world = argv[++i]
    else if (token === '--out') args.out = argv[++i]
    else if (token === '--const') args.constName = argv[++i]
    else if (token === '--help') {
      console.log('Usage: node scripts/generate-world-env.mjs --world <path> --out <path> --const <CONST_NAME>')
      process.exit(0)
    }
  }

  if (!/^[A-Z][A-Z0-9_]*$/.test(args.constName)) {
    throw new Error(`Invalid --const value "${args.constName}". Use SCREAMING_SNAKE_CASE.`)
  }

  return {
    worldPath: path.resolve(root, args.world),
    outPath: path.resolve(root, args.out),
    constName: args.constName,
  }
}

const Hex = z.string().regex(/^#([0-9a-fA-F]{3}|[0-9a-fA-F]{6})$/)
const tuple2 = z.tuple([z.number(), z.number()])
const tuple3 = z.tuple([z.number(), z.number(), z.number()])
const tuple4 = z.tuple([z.number(), z.number(), z.number(), z.number()])

const EnvironmentSchema = z.object({
  colors: z.object({
    road: Hex,
    line: Hex,
    park: Hex,
    trunk: Hex,
    leaf: Hex,
    canal: Hex,
  }),
  roads: z.object({
    strips: z.array(tuple4),
    lane_strips: z.array(tuple4),
  }),
  canal: z.object({
    position: tuple3,
    width: z.number().positive(),
    opacity: z.number().min(0).max(1),
  }),
  parks: z.array(tuple4),
  trees: z.object({
    positions: z.array(tuple2),
    trunk_size: tuple3,
    leaf_radius: z.number().positive(),
    trunk_y: z.number(),
    leaf_y: z.number(),
  }),
  decor_buildings: z.array(
    z.object({
      type: z.string().min(1),
      cx: z.number(),
      cz: z.number(),
      w: z.number().positive(),
      d: z.number().positive(),
      h: z.number().positive(),
      body_color: Hex,
      roof_color: Hex,
    }),
  ),
})

const WorldSchema = z.object({
  environment: EnvironmentSchema,
})

function resolveEnvironment(env) {
  const shophouseSpecs = []
  const midRiseSpecs = []

  for (const b of env.decor_buildings) {
    const spec = {
      cx: b.cx,
      cz: b.cz,
      w: b.w,
      d: b.d,
      h: b.h,
      bodyColor: b.body_color,
      roofColor: b.roof_color,
    }

    if (b.type === 'shophouse') shophouseSpecs.push(spec)
    else if (b.type === 'midrise' || b.type === 'tower') midRiseSpecs.push(spec)
    else {
      throw new Error(
        `Unsupported decor_buildings.type "${b.type}". Supported types: shophouse, midrise, tower.`,
      )
    }
  }

  return {
    colors: env.colors,
    roads: env.roads,
    canal: env.canal,
    parks: env.parks,
    trees: env.trees,
    shophouseSpecs,
    midRiseSpecs,
  }
}

const { worldPath, outPath, constName } = parseArgs(process.argv.slice(2))
const raw = fs.readFileSync(worldPath, 'utf8')
const parsedJson = JSON.parse(raw)
const parsed = WorldSchema.parse(parsedJson)
const resolved = resolveEnvironment(parsed.environment)

const generated = `/* AUTO-GENERATED by scripts/generate-world-env.mjs. DO NOT EDIT. */

export const ${constName} = ${JSON.stringify(resolved, null, 2)} as const
`

fs.writeFileSync(outPath, generated)
console.log(`Generated ${path.relative(root, outPath)} from ${path.relative(root, worldPath)}`)
